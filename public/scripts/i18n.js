const STORAGE_KEY = "playhouse-language";
const textOriginals = new WeakMap();

const normalizeText = (value) => value.replace(/\s+/g, " ").trim();

const translateValue = (value, dictionary) => {
  const normalized = normalizeText(value);
  return dictionary[normalized] || value;
};

const translateTextNode = (node, dictionary, language) => {
  const original = textOriginals.get(node) || normalizeText(node.nodeValue);
  if (!original) return;

  if (!textOriginals.has(node)) {
    textOriginals.set(node, original);
  }

  node.nodeValue = language === "ar" ? translateValue(original, dictionary) : original;
};

const translateElementAttributes = (element, dictionary, language) => {
  ["placeholder", "aria-label", "title"].forEach((attribute) => {
    if (!element.hasAttribute(attribute)) return;
    const dataKey = `i18nOriginal${attribute.replace(/(^|-)([a-z])/g, (_, __, char) => char.toUpperCase())}`;
    const original = element.dataset[dataKey] || element.getAttribute(attribute);

    if (!element.dataset[dataKey]) {
      element.dataset[dataKey] = original;
    }

    element.setAttribute(attribute, language === "ar" ? translateValue(original, dictionary) : original);
  });
};

const applyLanguage = (language) => {
  const dictionary = translations[language] || {};
  const isArabic = language === "ar";

  document.documentElement.lang = isArabic ? "ar" : "en";
  document.documentElement.dir = isArabic ? "rtl" : "ltr";
  document.body.classList.toggle("is-rtl", isArabic);

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!normalizeText(node.nodeValue)) return NodeFilter.FILTER_REJECT;
      if (node.parentElement?.closest("script, style, svg")) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });

  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => translateTextNode(node, dictionary, language));

  document.querySelectorAll("[placeholder], [aria-label], [title]").forEach((element) => {
    translateElementAttributes(element, dictionary, language);
  });

  document.querySelectorAll("[data-language-select]").forEach((select) => {
    select.value = language;
  });

  localStorage.setItem(STORAGE_KEY, language);
};

const bindLanguageSelectors = () => {
  document.querySelectorAll("[data-language-select]").forEach((select) => {
    select.addEventListener("change", () => applyLanguage(select.value));
  });
};

const initialLanguage = localStorage.getItem(STORAGE_KEY) || "en";

bindLanguageSelectors();
applyLanguage(initialLanguage);
